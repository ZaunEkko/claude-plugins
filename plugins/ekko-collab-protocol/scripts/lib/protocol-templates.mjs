function lines(...parts) {
  return `${parts.flat().join("\n")}\n`;
}

/** Returns the protocol files in write order: entry point, optional Claude pointer, status, records, ADRs. */
export function renderProtocol(config) {
  const t = TEXT[config.language];
  const multi = config.layout === "multi-repo";
  const map = multi ? config.repositories : config.modules;
  const commitRule = config.commitPolicy === "allowed" ? t.commitAllowed : t.commitAsk;

  const entry = lines(
    `# ${config.entrypoint}`,
    "",
    t.intro(config.projectName),
    "",
    `## ${t.start}`,
    "",
    t.order,
    "",
    t.status(config.statusFile),
    t.durable(config.adrDir),
    t.requirement(config.changesDir),
    t.verification,
    "",
    t.resume(config.statusFile),
    "",
    `## ${t.scopeHeading}`,
    "",
    multi ? t.scopeMulti : t.scopeSingle,
    ...(multi ? ["", t.childRules] : []),
    ...(map.length > 0 ? ["", ...map.map(t.mapLine)] : []),
    "",
    `## ${t.rolesHeading}`,
    "",
    t.roles(config.adrDir, config.statusFile),
    "",
    `## ${t.clarifyHeading}`,
    "",
    t.clarify,
    "",
    `## ${t.decisionHeading}`,
    "",
    t.decision(config.adrDir),
    "",
    `## ${t.implementHeading}`,
    "",
    t.implement,
    "",
    `## ${t.verifyHeading}`,
    "",
    ...(config.verifyCommands.length > 0
      ? [t.verifyLead, "", ...config.verifyCommands.map(t.commandLine)]
      : [t.verifyNone]),
    "",
    t.verifyRecord,
    "",
    `## ${t.syncHeading}`,
    "",
    t.sync(config.statusFile),
    "",
    `## ${t.boundaryHeading}`,
    "",
    `- ${t.writeScope(multi)}`,
    ...(config.protectedPaths.length > 0 ? [`- ${t.protectedPaths(config.protectedPaths)}`] : []),
    `- ${commitRule}`,
    `- ${t.remote}`,
    `- ${t.data}`,
    `- ${t.secrets}`,
    `- ${t.destructive}`
  );

  const files = [{ path: config.entrypoint, content: entry }];
  if (config.claudePointer && config.entrypoint !== "CLAUDE.md") {
    files.push({ path: "CLAUDE.md", content: lines("# CLAUDE.md", "", `@${config.entrypoint}`, "", t.claudeNote) });
  }
  files.push(
    {
      path: config.statusFile,
      content: lines(`# ${t.statusTitle}`, "", `## ${t.statusHeading}`, "", t.idle, "", t.statusGuide, "", t.statusFields)
    },
    {
      path: `${config.changesDir}/README.md`,
      content: lines(
        `# ${t.changesTitle}`,
        "",
        t.changesIntro,
        "",
        `## ${t.changesFieldsHeading}`,
        "",
        t.changesFields,
        "",
        t.changesSync,
        "",
        `## ${t.changesTemplateHeading}`,
        "",
        "```markdown",
        t.changesTemplate,
        "```"
      )
    },
    {
      path: `${config.adrDir}/README.md`,
      content: lines(`# ${t.adrTitle}`, "", t.adrIntro, "", `## ${t.adrIndexHeading}`, "", t.adrEmpty)
    }
  );
  return files;
}
